const fs=require('node:fs');
const {createHash}=require('node:crypto');
const files=['focus.mjs','social-core.mjs','journal.mjs','metronome.mjs','live-practice.mjs','auth-session.mjs','friends.mjs','cloud-journal.mjs','focus-ui.mjs','app.js'];
const bundle=files.map(file=>fs.readFileSync(file,'utf8').replace(/^import .*;\r?\n/gm,'').replace(/^export /gm,'')).join('\n');
fs.writeFileSync('app.bundle.js','/* repertoire — generated by node build.cjs */\n(()=>{\n'+bundle+'\n})();\n');
const hash=file=>createHash('sha256').update(fs.readFileSync(file)).digest('hex').slice(0,10);
const html=fs.readFileSync('index.html','utf8').replace(/href="style\.css(?:\?v=[^"]*)?"/,'href="style.css?v='+hash('style.css')+'"').replace(/src="app\.bundle\.js(?:\?v=[^"]*)?"/,'src="app.bundle.js?v='+hash('app.bundle.js')+'"');
fs.writeFileSync('index.html',html);
console.log('Built app.bundle.js');
